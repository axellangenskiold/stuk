import SwiftUI

struct DealItem: Identifiable, Hashable {
    let id = UUID()
    let brand: String
    let title: String
    let imageURL: String
    let accentColor: Color
    let buttonColor: Color
    let description: String
    let category: String
    let isCampaign: Bool
    let terms: String

    static func == (lhs: DealItem, rhs: DealItem) -> Bool { lhs.id == rhs.id }
    func hash(into hasher: inout Hasher) { hasher.combine(id) }
}

/// Build a stable Picsum URL from a brand seed.
private func pic(_ seed: String, _ w: Int = 600, _ h: Int = 800) -> String {
    "https://picsum.photos/seed/\(seed)/\(w)/\(h)"
}

