    /// Lookup table by category for HotDealsListView filtering.
    /// Falls back to a shuffled selection of all deals if no matches.
    static func byCategory(_ name: String?) -> [DealItem] {
        guard let name = name else { return hotDeals }
        let filtered = all.filter { $0.category == name }
        return filtered.isEmpty ? Array(all.shuffled().prefix(8)) : filtered
    }

    static var all: [DealItem] {
        hotDeals + popular + newDeals + tvStreaming + mobile + fashion + health + sport + jewelry + extras
    }

    /// Generates "Liknande rabatter" for a given deal — same category, excluding self.
    static func similar(to item: DealItem) -> [DealItem] {
        let sameCat = all.filter { $0.category == item.category && $0.id != item.id }
        return sameCat.isEmpty ? Array(all.shuffled().filter { $0.id != item.id }.prefix(4)) : sameCat
    }
